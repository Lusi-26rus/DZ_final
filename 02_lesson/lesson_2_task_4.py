def fizz_buzz(n):
    """
    Выводит числа от 1 до n с заменой:
    - Fizz, если число делится на 3
    - Buzz, если число делится на 5
    - FizzBuzz, если число делится на 3 и 5
    
    Параметры:
    n (int) - верхний предел диапазона
    """
    # Перебираем числа от 1 до n включительно
    for i in range(1, n + 1):
        # Проверяем делимость на 3 и 5
        if i % 3 == 0 and i % 5 == 0:
            print("FizzBuzz")
        # Проверяем делимость только на 3
        elif i % 3 == 0:
            print("Fizz")
        # Проверяем делимость только на 5
        elif i % 5 == 0:
            print("Buzz")
        # Если не подходит под условия выше - выводим число
        else:
            print(i)

# Пример использования функции
fizz_buzz(15)