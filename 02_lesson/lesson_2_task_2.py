def is_year_leap(year):
    """
    Проверяет, является ли год високосным
    
    Параметры:
    year (int) - год для проверки
    
    Возвращает:
    True - если год високосный
    False - если год не високосный
    """
    # Проверяем, делится ли год на 4 без остатка
    if year % 4 == 0:
        return True
    else:
        return False

# Пример использования функции
# Выбираем год для проверки (например, 2024)
test_year = 2024

# Вызываем функцию и сохраняем результат
result = is_year_leap(test_year)

# Выводим результат в консоль
print(f"год {test_year}: {result}")