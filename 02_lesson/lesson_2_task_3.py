def square(side):
    """
    Вычисляет площадь квадрата
    
    Параметры:
    side (float или int) - длина стороны квадрата
    
    Возвращает:
    float - площадь квадрата
    """
    # Площадь квадрата вычисляется как сторона в квадрате
    return side ** 2

# Пример использования функции
# Создаем переменную со стороной квадрата
side_length = 5

# Вычисляем площадь
area = square(side_length)

# Выводим результат
print(f"Площадь квадрата со стороной {side_length}: {area}")