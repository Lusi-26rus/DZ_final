def print_number(num):
    print(num, end='')  # Используем end='' чтобы числа выводились в одну строку

# Вызываем функцию 11 раз с соответствующими цифрами
print_number(8)   # Первая цифра
print_number(8)   # Вторая цифра
print_number(0)   # Третья цифра
print_number(0)   # Четвертая цифра
print_number(5)   # Пятая цифра
print_number(5)   # Шестая цифра
print_number(5)   # Седьмая цифра
print_number(3)   # Восьмая цифра
print_number(5)   # Девятая цифра
print_number(3)   # Десятая цифра
print_number(5)   # Одиннадцатая цифра